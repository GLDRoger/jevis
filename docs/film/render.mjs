#!/usr/bin/env node
// Renders film.html frame by frame in headless Chromium, then mixes the sound and encodes the MP4.
//   node docs/film/render.mjs                    full film -> docs/film/out/jevis-launch.mp4
//   node docs/film/render.mjs --grid 36          contact sheet of 36 evenly spaced frames
//   node docs/film/render.mjs --grid 12 --frames 349,360,371
//   node docs/film/render.mjs --only 349,800     full-size PNGs
//   node docs/film/render.mjs --reuse-frames --crf 22   re-mix and re-encode from out/frames
//   node docs/film/render.mjs --audio            only the mix (out/mix.wav), plus a spectrogram
// Chromium: $CHROME, else Playwright's preinstalled build, else the system Chrome.
import { chromium } from 'playwright-core';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { cpus } from 'node:os';
import { fetchAudio, mix } from './audio.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const args = process.argv.slice(2);
const opt = name => { const i = args.indexOf(`--${name}`); return i < 0 ? undefined : (args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : true); };
const OUT = resolve(opt('out') || join(HERE, 'out'));
mkdirSync(OUT, { recursive: true });

// The lesson wall reads the real wiki, so its count is whatever the repository holds.
const titles = [];
for (const d of readdirSync(join(ROOT, 'wiki')).sort()) {
  const dir = join(ROOT, 'wiki', d); let files; try { files = readdirSync(dir).sort(); } catch { continue; }
  for (const f of files) if (f.endsWith('.md')) { const m = /^title:\s*(.+)$/m.exec(readFileSync(join(dir, f), 'utf8')); if (m) titles.push(m[1].trim()); }
}
writeFileSync(join(HERE, 'lessons.js'), `// Generated by render.mjs from wiki/*/*.md titles.\nwindow.LESSONS = ${JSON.stringify(titles, null, 0)};\n`);

function chromePath() {
  if (process.env.CHROME) return process.env.CHROME;
  const pw = process.env.PLAYWRIGHT_BROWSERS_PATH || '/opt/pw-browsers';
  if (existsSync(pw)) for (const d of readdirSync(pw).sort().reverse()) {
    const p = join(pw, d, 'chrome-linux', 'chrome'); if (d.startsWith('chromium-') && existsSync(p)) return p;
  }
  for (const p of ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium']) if (existsSync(p)) return p;
  throw new Error('No Chrome found; set CHROME');
}

async function openFilm(browser) {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  const blocked = [];
  await page.route('**/*', r => (r.request().url().startsWith('file:') ? r.continue() : (blocked.push(r.request().url()), r.abort())));
  await page.goto(pathToFileURL(join(HERE, 'film.html')).href + '?render=1');
  await page.waitForFunction(() => window.FILM && window.FILM.ready);
  const fontOk = await page.evaluate(() => document.fonts.check('40px Tanker'));
  if (!fontOk) throw new Error('Tanker font did not load');
  return { page, blocked };
}

async function renderFrames(browser, frames, dir, workers) {
  mkdirSync(dir, { recursive: true });
  const queue = frames.slice(); let done = 0; const t0 = Date.now();
  const blocked = new Set();
  await Promise.all(Array.from({ length: Math.min(workers, frames.length) }, async () => {
    const { page, blocked: b } = await openFilm(browser);
    for (let f; (f = queue.shift()) !== undefined;) {
      const url = await page.evaluate(n => { window.FILM.draw(n); return window.FILM.canvas.toDataURL('image/png'); }, f);
      writeFileSync(join(dir, `f${String(f).padStart(5, '0')}.png`), Buffer.from(url.split(',')[1], 'base64'));
      if (++done % 100 === 0) process.stdout.write(`  ${done}/${frames.length} frames, ${((Date.now() - t0) / done).toFixed(0)} ms each\n`);
    }
    b.forEach(u => blocked.add(u)); await page.close();
  }));
  console.log(`external requests: ${blocked.size ? [...blocked].join(', ') : 'none'}`);
}

const browser = await chromium.launch({ executablePath: chromePath(), args: ['--disable-gpu', '--font-render-hinting=none'] });
const { page } = await openFilm(browser);
const film = await page.evaluate(() => ({ N: FILM.N, FPS: FILM.FPS, DUR: FILM.DUR, MUSIC: FILM.MUSIC, cues: FILM.cues, typed: FILM.typed }));
await page.close();
writeFileSync(join(OUT, 'cues.json'), JSON.stringify(film.cues, null, 1));
const workers = +(opt('workers') || Math.max(1, cpus().length));

if (opt('only')) {
  const frames = String(opt('only')).split(',').map(Number);
  await renderFrames(browser, frames, OUT, workers);
  console.log(frames.map(f => join(OUT, `f${String(f).padStart(5, '0')}.png`)).join('\n'));
} else if (opt('grid')) {
  const n = +opt('grid');
  const frames = opt('frames') ? String(opt('frames')).split(',').map(Number) : Array.from({ length: n }, (_, i) => Math.round(i * (film.N - 1) / (n - 1)));
  const dir = join(OUT, 'grid'); rmSync(dir, { recursive: true, force: true });
  await renderFrames(browser, frames, dir, workers);
  const cols = 6, rows = Math.ceil(frames.length / cols);
  const list = join(dir, 'list.txt'); writeFileSync(list, frames.map(f => `file 'f${String(f).padStart(5, '0')}.png'`).join('\n'));
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', list, '-vf',
    `scale=480:-1,drawtext=text='%{frame_num}':x=8:y=8:fontcolor=white:fontsize=18:box=1:boxcolor=black@0.6:start_number=0,tile=${cols}x${rows}`, '-frames:v', '1', join(OUT, 'grid.png')]);
  console.log(`frames: ${frames.join(',')}\n${join(OUT, 'grid.png')}`);
} else {
  const audioDir = join(HERE, '.audio');
  fetchAudio(audioDir);
  const wav = mix({ dir: audioDir, cues: film.cues, film, out: OUT });
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', wav, '-lavfi', 'showspectrumpic=s=1800x400:legend=1:scale=log', join(OUT, 'spectrum.png')]);
  console.log(`audio: ${wav}`);
  if (!opt('audio')) {
    const dir = join(OUT, 'frames'); if (!opt('from') && !opt('to') && !opt('reuse-frames')) rmSync(dir, { recursive: true, force: true }); // a range re-renders into the existing frames
    const from = +(opt('from') || 0), to = +(opt('to') || film.N - 1);
    if (!opt('reuse-frames')) await renderFrames(browser, Array.from({ length: to - from + 1 }, (_, i) => from + i), dir, workers);
    const mp4 = join(OUT, 'jevis-launch.mp4');
    execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-framerate', String(film.FPS), '-start_number', '0', '-i', join(dir, 'f%05d.png'), '-i', wav,
      '-c:v', 'libx264', '-preset', 'slow', '-tune', 'animation', '-crf', String(opt('crf') || 25), '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-c:a', 'aac', '-b:a', '192k', '-shortest', mp4]);
    console.log(mp4);
  }
}
await browser.close();
